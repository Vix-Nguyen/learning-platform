import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

process.loadEnvFile('.env');
const origin = 'https://fluentpath-ielts.nguyenvipy.workers.dev';
const authorization = `Basic ${Buffer.from(`${process.env.AUTH_USERNAME}:${process.env.AUTH_PASSWORD}`).toString('base64')}`;
const headers = { Authorization: authorization };
const anonymous = await fetch(origin);
assert.equal(anonymous.status, 401, 'Anonymous HTML must be protected');
assert.match(anonymous.headers.get('www-authenticate') || '', /^Basic/);
const page = await fetch(origin, { headers });
assert.equal(page.status, 200, 'Authenticated HTML must load');
const html = await page.text();
assert.match(html, /FluentPath/);
assert.equal(page.headers.get('cache-control'), 'private, no-store');
assert.equal(page.headers.get('x-content-type-options'), 'nosniff');
assert.match(page.headers.get('strict-transport-security') || '', /max-age/);
const session = await fetch(`${origin}/api/session`, { headers });
assert.equal(session.status, 200);
const state = await session.json();
assert.equal(state.authenticated, true);
assert.equal(state.authEnabled, false);
const ai = await fetch(`${origin}/api/mentor`, { method: 'POST', headers: { ...headers, Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ mode: 'chat', language: 'vi', messages: [{ role: 'user', content: 'Explain the difference between affect and effect.' }] }) });
assert.equal(ai.status, state.aiConfigured ? 200 : 503);
const crossOrigin = await fetch(`${origin}/api/mentor`, { method: 'POST', headers: { ...headers, Origin: 'https://example.com', 'Content-Type': 'application/json' }, body: '{}' });
assert.equal(crossOrigin.status, 403);
const assetPath = /src="([^"]+\.js)"/.exec(html)?.[1];
assert.ok(assetPath);
assert.equal((await fetch(new URL(assetPath, origin))).status, 401, 'Anonymous JS must be protected');
const asset = await fetch(new URL(assetPath, origin), { headers });
assert.equal(asset.status, 200);
assert.match(asset.headers.get('content-type') || '', /javascript/);
const htmlFile = await readFile('dist/index.html', 'utf8');
assert.equal(html, htmlFile, 'Deployed HTML must match the final local build');
const http = await fetch(origin.replace('https:', 'http:'), { redirect: 'manual' });
assert.ok([301, 302, 307, 308].includes(http.status), 'HTTP must redirect to HTTPS');
assert.match(http.headers.get('location') || '', /^https:/);
console.log(JSON.stringify({ url: origin, anonymous: anonymous.status, authenticated: page.status, session: session.status, ai: ai.status, crossOrigin: crossOrigin.status, protectedAsset: true, exactBuild: true, httpRedirect: http.status, aiConfigured: state.aiConfigured }, null, 2));
